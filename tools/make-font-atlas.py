#!/usr/bin/env python3
"""Turn a TrueType font into a C header the player can draw.

The console build has no font rasteriser, so glyphs are rendered here (on a PC,
with Pillow) into an 8-bit alpha atlas plus per-glyph metrics, and ui.c blits
them as one texture. Anti-aliasing survives because the atlas is 8-bit.

    python3 tools/make-font-atlas.py Font.ttf --name font_inter --size 36 \
        > src/font_inter.h

The header defines `ui_font` (a UiFontAtlas from font_atlas.h) so it can be
dropped in with a single -D.
"""
import argparse
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf")
    ap.add_argument("--name", default="ui_font_data")
    ap.add_argument("--size", type=int, default=36, help="pixel size of the atlas")
    args = ap.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    ascent, descent = font.getmetrics()

    # Everything below is measured from the BASELINE (anchor "ls"), not from the
    # ascender line: that is what the renderer positions glyphs against.
    # Align faces by cap height as well, so a face with deep ascender space does
    # not sit several pixels lower in the same layout than one without.
    caps = [font.getbbox(c, anchor="ls")[1] for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"]
    ascent = -min(caps) if caps else ascent

    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        bbox = font.getbbox(ch, anchor="ls")
        if bbox is None:
            glyphs.append((0, 0, 0, 0, round(font.getlength(ch)), 0))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            glyphs.append((0, 0, 0, 0, round(font.getlength(ch)), 0))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, anchor="ls", fill=255)
        glyphs.append((img, w, h, y0, round(font.getlength(ch))))

    # shelf pack: tallest first, then left to right
    order = sorted(range(len(glyphs)), key=lambda i: -(glyphs[i][2] if len(glyphs[i]) == 5 else 0))
    AW = 512
    x = y = 0
    shelf = 0
    placed = {}
    for i in order:
        g = glyphs[i]
        if len(g) != 5:
            continue
        img, w, h, y0, adv = g
        if x + w + 1 > AW:
            x = 0
            y += shelf + 1
            shelf = 0
        placed[i] = (x, y)
        x += w + 1
        shelf = max(shelf, h)
    AH = y + shelf + 1

    atlas = Image.new("L", (AW, AH), 0)
    for i, (px, py) in placed.items():
        atlas.paste(glyphs[i][0], (px, py))

    out = sys.stdout
    out.write("/* %s.h - generated by tools/make-font-atlas.py, do not edit.\n"
              " * Source font: %s (OFL). Atlas %dx%d, base size %d.\n"
              " */\n" % (args.name, args.ttf.split("/")[-1], AW, AH, args.size))
    out.write("#ifndef FONT_ATLAS_DATA_H\n#define FONT_ATLAS_DATA_H\n\n")
    out.write('#include "font_atlas.h"\n\n')
    out.write("#define UI_FONT_BASE_H %d\n#define UI_FONT_ASCENT %d\n\n" % (args.size, ascent))

    data = atlas.tobytes()
    out.write("static const unsigned char ui_font_alpha[%d] = {\n" % len(data))
    line = "    "
    for i, b in enumerate(data):
        item = "%d," % b
        if len(line) + len(item) > 96:
            out.write(line.rstrip() + "\n")
            line = "    "
        line += item
    out.write(line.rstrip() + "\n};\n\n")

    out.write("static const UiGlyphAtlas ui_font_glyphs[%d] = {\n" % (LAST - FIRST + 1))
    for code in range(FIRST, LAST + 1):
        i = code - FIRST
        g = glyphs[i]
        if i in placed:
            _, w, h, y0, adv = g
            px, py = placed[i]
            out.write("    {%d,%d,%d,%d,%d,%d},   /* %s */\n" % (px, py, w, h, adv, y0, repr(chr(code))))
        else:
            adv = g[4] if len(g) == 5 else g[4]
            out.write("    {0,0,0,0,%d,0},\n" % adv)
    out.write("};\n\n")

    out.write("static const UiFontAtlas ui_font = {\n"
              "    ui_font_alpha, %d, %d,\n"
              "    ui_font_glyphs, %d, %d, UI_FONT_BASE_H, UI_FONT_ASCENT\n"
              "};\n\n" % (AW, AH, FIRST, LAST - FIRST + 1))
    out.write("#endif /* FONT_ATLAS_DATA_H */\n")


if __name__ == "__main__":
    main()
