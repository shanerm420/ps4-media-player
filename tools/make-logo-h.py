#!/usr/bin/env python3
"""Regenerate src/ps4logo.h from the PlayStation 4 wordmark.

The logo is public-domain text/geometry (Wikimedia Commons,
File:PlayStation 4 logo and wordmark.svg). It is thresholded to a 1-bit mask
and stored as horizontal spans so the player can draw it with plain SDL rects:
no PNG decoder, no SDL_image, no asset to ship.

    python3 tools/make-logo-h.py ps4-logo.png > src/ps4logo.h

Needs Pillow.
"""
import sys

from PIL import Image

HEIGHT = 40
THRESHOLD = 96


def main(path):
    im = Image.open(path).convert("RGBA")
    width = round(im.width * HEIGHT / im.height)
    im = im.resize((width, HEIGHT), Image.LANCZOS)
    alpha = im.split()[3]

    runs = []
    for y in range(HEIGHT):
        x = 0
        while x < width:
            if alpha.getpixel((x, y)) > THRESHOLD:
                start = x
                while x < width and alpha.getpixel((x, y)) > THRESHOLD:
                    x += 1
                runs.append((start, y, x - start))
            else:
                x += 1

    out = sys.stdout
    out.write("/* ps4logo.h - the PlayStation 4 wordmark as drawing data.\n"
              " *\n"
              " * Generated by tools/make-logo-h.py from the official public-domain\n"
              " * wordmark (Wikimedia Commons, File:PlayStation 4 logo and wordmark.svg).\n"
              " * 1-bit mask at %dx%d, stored as horizontal spans, so ui.c draws it\n"
              " * with the same SDL primitives as the rest of the interface.\n"
              " */\n" % (width, HEIGHT))
    out.write("#ifndef PS4LOGO_H\n#define PS4LOGO_H\n\n")
    out.write("#define PS4_LOGO_W %d\n#define PS4_LOGO_H %d\n\n" % (width, HEIGHT))
    out.write("static const unsigned short ps4_logo_runs[][3] = {\n")
    line = "    "
    for x, y, n in runs:
        item = "{%d,%d,%d}," % (x, y, n)
        if len(line) + len(item) > 96:
            out.write(line.rstrip() + "\n")
            line = "    "
        line += item
    if line.strip():
        out.write(line.rstrip() + "\n")
    out.write("};\n\n")
    out.write("#define PS4_LOGO_RUNS (sizeof(ps4_logo_runs)/sizeof(ps4_logo_runs[0]))\n\n")
    out.write("#endif /* PS4LOGO_H */\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "ps4-logo.png")
