#!/bin/sh
# push-docs.sh - publish the linked knowledge tree to GitHub, bottom-up.
#
#   1. regenerate the tree from the canonical docs (tools/publish-docs.py)
#   2. clone the repository into _scratch/ (never over your working copy)
#   3. commit in dependency order: leaves, then the pages that link to them,
#      then the indexes that link to those
#   4. push, once, if you are authenticated
#
# Usage:
#   gh auth login          # once, with your GitHub account
#   sh tools/push-docs.sh            # stage and push
#   DRY=1 sh tools/push-docs.sh      # stage and show the commits, do not push
#
# Nothing in the project folder is modified except the regenerated files under
# _scratch/publish, which is scratch space by rule.

set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

OWNER=shanerm420
REPO=ps4-media-player
URL="https://github.com/$OWNER/$REPO.git"

echo "== regenerate"
python3 tools/publish-docs.py

WORK="_scratch/push-$(date +%Y%m%d-%H%M%S)"
echo "== clone into $WORK"
git clone --depth 1 "$URL" "$WORK"
git -C "$WORK" config user.name "shanerm420"
git -C "$WORK" config user.email "shanerm420@users.noreply.github.com"

echo "== copy the published tree in"
cp -R _scratch/publish/. "$WORK"/

# The README is the project's own, with a pointer block in front. It used to be
# the clone's copy, so the repository kept whatever README it had the first time
# and never the current one (2026-11-24 review, finding 8).
cat > "$WORK/README.md" <<'BLOCK'
## Documentation

Rules, measured facts and the project's build history live in
[docs/](docs/README.md). If you are an AI agent, read [AGENTS.md](AGENTS.md)
first - it states the rules, the read order and what is known versus assumed.

BLOCK
cat README.md >> "$WORK/README.md"

# The tree the documentation describes. Until 2026-11-24 only docs were
# published, so the repository carried a 2026-11-21 source next to 2026-11-24
# documentation (2026-11-24 review, finding 1: the same seam behind five more).
echo "== copy the source the docs describe"
rsync -a --exclude '_scratch' src test tools third_party Makefile LICENSE \
      THIRD_PARTY.md .gitignore "$WORK"/
# preview/ carries ~790 MB of screenshots; only its sources belong in the repo.
rsync -a --include '*.c' --include '*.h' --include 'Makefile' --include '*.png' \
      --exclude '*' preview/ "$WORK/preview/"

commit() {
    msg=$1
    shift
    git -C "$WORK" add -- "$@" >/dev/null 2>&1 || true
    if git -C "$WORK" diff --cached --quiet; then
        echo "   (nothing to commit: $msg)"
        return 0
    fi
    git -C "$WORK" commit -q -m "$msg"
    echo "   committed: $msg"
}

echo "== commit 1/4 source: the code the docs describe"
commit "source: publish the code the documentation describes

src/, test/, preview/, third_party/, tools/ and the Makefile were never
published; the repository carried a 2026-11-21 source next to 2026-11-24
documentation, so documented fixes looked missing from the tree." \
    src test preview third_party Makefile LICENSE THIRD_PARTY.md .gitignore

echo "== commit 2/4 leaves: rules, amendments, history"
commit "docs: publish rules, amendments and build history

Each rule gets its own page with its status and the evidence behind it, so a
broken claim fails in one place instead of in five summaries.

Generated by tools/publish-docs.py from MANIFEST §9 and AGENTS.md." \
    docs/rules docs/amendments docs/HISTORY.md

echo "== commit 3/4 middle: the manifest in twelve parts"
commit "docs: publish the manifest in twelve linked parts

Section references become real links, so §9 in one page opens §9's page.

Generated by tools/publish-docs.py from MANIFEST.md." \
    docs/manifest

echo "== commit 4/4 top: index, rules file, status board, tools, CI"
commit "docs: publish the index, rules file, status board and checkers

AGENTS.md at the repository root is the file an AI agent reads first; README
points into docs/. tools/check-links.py runs in CI on every push, so a broken
link or a dangling anchor fails the build." \
    README.md AGENTS.md docs/README.md docs/PLAN.md \
    docs/STATUS.html docs/RULES.index tools .github CHECKSUMS.txt \
    PIGLET-NOTES.md ROUND-NOTES.md APPENDIX-LOGS.md

echo "== what was staged"
git -C "$WORK" --no-pager log --oneline -4

if [ "${DRY:-0}" = "1" ]; then
    echo "== DRY: staged only. Publish with: sh tools/push-docs.sh"
    exit 0
fi

if [ -n "${GH_TOKEN:-}" ]; then
    # A token in the environment is used without ever being written to disk,
    # logged, or placed in a remote URL: it goes in as a one-off auth header.
    echo "== push with GH_TOKEN (never printed)"
    _auth=$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 -w0)
    git -C "$WORK" -c http.extraheader="Authorization: Basic $_auth" \
        push origin HEAD:main
    unset _auth
elif gh auth status >/dev/null 2>&1; then
    echo "== push with the gh login"
    git -C "$WORK" push origin HEAD:main
else
    echo "== NOT PUSHED: no credential in this environment."
    echo "   Either: gh auth login      (once, in this shell)"
    echo "   Or:     GH_TOKEN=<pat> sh tools/push-docs.sh"
    echo "   Or:     sh tools/push-docs.sh on the machine where you are signed in."
    exit 1
fi
TAG=${TAG:-docs-$(date +%Y-%m-%d-%H%M)}
echo "== tag $TAG"
git -C "$WORK" tag -a "$TAG" -m "published docs, $TAG"
if [ -n "${GH_TOKEN:-}" ]; then
    _auth=$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 -w0)
    git -C "$WORK" -c http.extraheader="Authorization: Basic $_auth" \
        push origin "refs/tags/$TAG"
    unset _auth
else
    git -C "$WORK" push origin "refs/tags/$TAG"
fi
echo "== done: https://github.com/$OWNER/$REPO (tag $TAG)"
