#!/usr/bin/env python3
"""Turn the 1000 px emblem art into the bytes the player draws.

The old route traced the art into flat color runs, which is why the header
emblem looked like pixel steps. This keeps every pixel of the art, cropped to
its alpha and resampled once with LANCZOS, then embeds it as a PNG the console
decodes at startup with the stb_image it already carries. The player blits one
texture, so the edges arrive already smoothed - the same way the original does.
"""
import sys
from PIL import Image

src = sys.argv[1] if len(sys.argv) > 1 else "../PS4_emblem_transparent_1000px (2).png"
WIDTH = 600            # 2x the 300 px it is drawn at, so the blit downscales

im = Image.open(src).convert("RGBA")
im = im.crop(im.split()[3].getbbox())
h = max(1, round(im.height * WIDTH / im.width))
im = im.resize((WIDTH, h), Image.LANCZOS)
# the LANCZOS halo can leave a nearly invisible edge; clean it so the keyline
# stays crisp against the header
px = im.load()
for y in range(h):
    for x in range(WIDTH):
        r, g, b, a = px[x, y]
        if a < 6:
            px[x, y] = (0, 0, 0, 0)

out = "src/emblem.png"
im.save(out)
data = open(out, "rb").read()

with open("src/emblem_img.h", "w") as f:
    f.write("/* Generated by tools/make-emblem-png.py - do not edit. */\n")
    f.write("#ifndef PS4_EMBLEM_IMG_H\n#define PS4_EMBLEM_IMG_H\n\n")
    f.write("#define EMBLEM_IMG_W %d\n#define EMBLEM_IMG_H %d\n\n" % (WIDTH, h))
    f.write("static const unsigned char emblem_img_png[%d] = {\n" % len(data))
    for i in range(0, len(data), 20):
        f.write(",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n\n#endif\n")

print("emblem %dx%d from %s, png %d bytes -> src/emblem_img.h" % (WIDTH, h, src, len(data)))
