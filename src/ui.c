static int    s_w = DESIGN_W;
static int    s_h = DESIGN_H;
/* One factor for glyph sizes: the layout is authored at 1080p, so at any other
 * output size text shrinks and grows with the panels instead of drifting off
 * them. Positions use px()/py(); this only sets how big a glyph is drawn. */
static double s_scale = 1.0;

static int px(int u) { return (int)((long)u * s_w / DESIGN_W + (u < 0 ? -0.5 : 0.5)); }
static int py(int u) { return (int)((long)u * s_h / DESIGN_H + (u < 0 ? -0.5 : 0.5)); }

/* ---------------------------------------------------------------- basics -- */

static void col(SDL_Renderer *r, int cr, int cg, int cb)
{
    SDL_SetRenderDrawColor(r, (Uint8)cr, (Uint8)cg, (Uint8)cb, 255);
}

static void rect(SDL_Renderer *r, int x, int y, int w, int h)
{
    SDL_Rect q;
    if (w <= 0 || h <= 0)
        return;
    q.x = px(x); q.y = py(y);
    q.w = px(w); q.h = py(h);
    if (q.w < 1) q.w = 1;
    if (q.h < 1) q.h = 1;
    SDL_RenderFillRect(r, &q);
}

/* Rounded rect from a middle rect plus four quarter discs, so it needs no
 * geometry API the PS4 SDL2 backend might not have. */
static void round_rect(SDL_Renderer *r, int x, int y, int w, int h, int radius)
{
    int i;

    if (radius*2 > w) radius = w/2;
    if (radius*2 > h) radius = h/2;
    if (radius < 1) { rect(r, x, y, w, h); return; }

    rect(r, x + radius, y, w - 2*radius, h);
    rect(r, x, y + radius, radius, h - 2*radius);
    rect(r, x + w - radius, y + radius, radius, h - 2*radius);

    /* Each corner row is filled from the inside out: at the very top edge only
     * the pixel next to the straight side is kept, widening to the full radius
     * at the row where the corner ends. Getting this backwards fills the square
     * corner instead of rounding it, which shows up as notches on every panel. */
    for (i = 0; i < radius; i++) {
        double dy   = i + 0.5;
        double span = sqrt((double)radius*radius - (radius - dy)*(radius - dy));
        int    wid  = (int)(span + 0.5);

        if (wid <= 0)
            continue;
        rect(r, x + radius - wid, y + i, wid, 1);            /* top-left  */
        rect(r, x + w - radius,   y + i, wid, 1);            /* top-right */
        rect(r, x + radius - wid, y + h - 1 - i, wid, 1);    /* bot-left  */
        rect(r, x + w - radius,   y + h - 1 - i, wid, 1);    /* bot-right */
    }
}

/* Same shape as rect(), with an alpha, for things that fade. */
static void rect_a(SDL_Renderer *r, int x, int y, int w, int h,
                   int cr, int cg, int cb, int alpha)
{
    SDL_Rect q;

    if (w <= 0 || h <= 0 || alpha <= 0)
        return;
    if (alpha > 255) alpha = 255;
    q.x = px(x); q.y = py(y); q.w = px(w); q.h = py(h);
    if (q.w < 1) q.w = 1;
    if (q.h < 1) q.h = 1;

    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(r, (Uint8)cr, (Uint8)cg, (Uint8)cb, (Uint8)alpha);
    SDL_RenderFillRect(r, &q);
    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_NONE);
}

static void round_rect_a(SDL_Renderer *r, int x, int y, int w, int h,
                         int radius, int cr, int cg, int cb, int alpha)
{
    int i;

    if (radius*2 > w) radius = w/2;
    if (radius*2 > h) radius = h/2;
    if (radius < 1) { rect_a(r, x, y, w, h, cr, cg, cb, alpha); return; }

    rect_a(r, x + radius, y, w - 2*radius, h, cr, cg, cb, alpha);
    rect_a(r, x, y + radius, radius, h - 2*radius, cr, cg, cb, alpha);
    rect_a(r, x + w - radius, y + radius, radius, h - 2*radius, cr, cg, cb, alpha);

    for (i = 0; i < radius; i++) {
        double dy   = i + 0.5;
        double span = sqrt((double)radius*radius - (radius - dy)*(radius - dy));
        int    wid  = (int)(span + 0.5);

        if (wid <= 0)
            continue;
        rect_a(r, x + radius - wid, y + i, wid, 1, cr, cg, cb, alpha);
        rect_a(r, x + w - radius,   y + i, wid, 1, cr, cg, cb, alpha);
        rect_a(r, x + radius - wid, y + h - 1 - i, wid, 1, cr, cg, cb, alpha);
        rect_a(r, x + w - radius,   y + h - 1 - i, wid, 1, cr, cg, cb, alpha);
    }
}

/* ---------------------------------------------------------------- text ---- */

#ifdef UI_FONT_ATLAS
/* The three sizes the layout asks for, in pixels of line height. */
static int font_px(int scale)
{
    return scale <= 1 ? TYPE_CAPTION
         : (scale == 2 ? TYPE_BODY
         : (scale == 3 ? TYPE_TITLE : TYPE_HERO));
}
#endif

/* Width in *design* units, so every layout calculation stays in one space no
 * matter what the surface is. */
static int text_width(const char *s, int scale)
{
#ifdef UI_FONT_ATLAS
    int wpx = ui_font_width(&ui_font, px(font_px(scale)), s);

    if (s_scale <= 0.0)
        return wpx;
    return (int)((double)wpx / s_scale + 0.5);
#else
    int n = 0;
    for (; s && *s; s++)
        n++;
    return n * (8*scale + scale/2);
#endif
}

#ifndef UI_FONT_ATLAS
static void draw_text(SDL_Renderer *r, int x, int y, int scale, const char *s)
{
    if (!s)
        return;
    for (; *s; s++) {
        const unsigned char *glyph = media_font_char((unsigned char)*s);
        int row, cell = scale + (scale > 1);
        for (row = 0; row < 8; row++) {
            unsigned char bits = glyph[row];
            int c;
            for (c = 0; c < 8; c++)
                if (bits & (1u << c))
                    rect(r, x + c*scale, y + row*scale, cell, cell);
        }
        x += 8*scale + scale/2;
    }
}
#endif /* !UI_FONT_ATLAS */

static void text_at(SDL_Renderer *r, int x, int y, int scale, const char *s,
                    int cr, int cg, int cb)
{
#ifdef UI_FONT_ATLAS
    /* rasterise at the scaled size but place it in design coordinates */
    ui_font_draw(r, &ui_font, px(x), py(y), px(font_px(scale)), s, cr, cg, cb);
#else
    col(r, cr, cg, cb);
    draw_text(r, x, y, scale, s);
#endif
}

static void text_at_a(SDL_Renderer *r, int x, int y, int scale, const char *s,
                      int cr, int cg, int cb, int alpha)
{
    if (alpha <= 0)
        return;
#ifdef UI_FONT_ATLAS
    ui_font_draw_a(r, &ui_font, px(x), px(y), px(font_px(scale)), s,
                   cr, cg, cb, alpha);
#else
    if (alpha > 96)                     /* the pixel font has no alpha path */
        text_at(r, x, y, scale, s, cr, cg, cb);
#endif
}

static void text_center(SDL_Renderer *r, int cx, int y, int scale, const char *s,
                        int cr, int cg, int cb)
{
    text_at(r, cx - text_width(s, scale)/2, y, scale, s, cr, cg, cb);
}

static void text_right(SDL_Renderer *r, int right_x, int y, int scale,
                       const char *s, int cr, int cg, int cb)
{
    text_at(r, right_x - text_width(s, scale), y, scale, s, cr, cg, cb);
}

/* Shortens src with "..." so it fits max_px at this scale. */
static void fit_text(char *dst, size_t dstsz, const char *src, int max_px, int scale)
{
    size_t n, cut;

    if (dstsz < 8) {
        snprintf(dst, dstsz, "%s", src);
        return;
    }
    n = strlen(src);
    if (n > dstsz - 1)
        n = dstsz - 1;
    memcpy(dst, src, n);
    dst[n] = '\0';
    if (text_width(dst, scale) <= max_px)
        return;

    /* measured, not estimated: the two text backends have different widths */
    for (cut = n; cut > 1; cut--) {
        dst[cut] = '\0';
        if (cut + 3 >= dstsz)
            continue;
        memcpy(dst + cut, "...", 4);
        if (text_width(dst, scale) <= max_px)
            return;
    }
    snprintf(dst, dstsz, "...");
}

static void fmt_time(char *buf, size_t n, double sec)
{
    long t;
    if (!(sec > 0.0))
        snprintf(buf, n, "--:--");
    else {
        t = (long)sec;
        snprintf(buf, n, "%ld:%02ld", t/60, t%60);
    }
}

