/* Where the picture lands. FIT keeps the whole frame visible, FILL crops the
 * overhanging edges to cover the screen, STRETCH ignores the aspect ratio. */
static void video_dest_rect(int fw, int fh, int mode, SDL_Rect *dst)
{
    double sa = (double)fw / (double)fh;
    double da = (double)s_w / (double)s_h;

    dst->x = 0;
    dst->y = 0;
    dst->w = s_w;
    dst->h = s_h;
    if (mode != UI_ASPECT_STRETCH) {
        int cover = (mode == UI_ASPECT_FILL);

        if (sa > da) {
            if (cover) { dst->h = s_h; dst->w = (int)((double)s_h * sa + 0.5); }
            else       { dst->w = s_w; dst->h = (int)((double)s_w / sa + 0.5); }
        } else {
            if (cover) { dst->w = s_w; dst->h = (int)((double)s_w / sa + 0.5); }
            else       { dst->h = s_h; dst->w = (int)((double)s_h * sa + 0.5); }
        }
        dst->x = (s_w - dst->w) / 2;
        dst->y = (s_h - dst->h) / 2;
    }
    /* A rect within a few percent of the frame size is drawn as a straight
     * copy, not a 0.99x scale. The software renderer's scaled blit measured
     * ~45 ms a frame at 1920x1088 while its unscaled one is a row copy; the
     * few rows that fall outside are clipped, which at this ratio is a 0.3%
     * crop nobody can see. */
    if (mode != UI_ASPECT_STRETCH && dst->w < fw && dst->w > 0 &&
        fw - dst->w <= fw / 32) {
        dst->w = fw;
        dst->h = fh;
        dst->x = (s_w - fw) / 2;
        dst->y = (s_h - fh) / 2;
    }
}

/* Brightness is a display grade, not a decoder setting: a black or white veil
 * over the picture rect, so it costs one blended fill instead of touching
 * every pixel and it looks the same in the preview as on the console. */
static void brightness_veil(SDL_Renderer *r, const SDL_Rect *dst, int b)
{
    SDL_Rect q;
    int      alpha;

    if (!b)
        return;
    q = *dst;
    if (q.x < 0) { q.w += q.x; q.x = 0; }
    if (q.y < 0) { q.h += q.y; q.y = 0; }
    if (q.x + q.w > s_w) q.w = s_w - q.x;
    if (q.y + q.h > s_h) q.h = s_h - q.y;
    if (q.w <= 0 || q.h <= 0)
        return;

    alpha = b > 0 ? b * 3 / 2 : -b * 255 / 100;
    if (alpha > 255) alpha = 255;

    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(r, b > 0 ? 255 : 0, b > 0 ? 255 : 0,
                           b > 0 ? 255 : 0, (Uint8)alpha);
    SDL_RenderFillRect(r, &q);
    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_NONE);
}

/* Subtitles sit on a plate above the transport bar: white on semi-transparent
 * black, word-wrapped to four lines, so they stay readable over a bright sky
 * as well as a night scene. */
static void draw_subtitles(SDL_Renderer *r, const char *text, int size, int bottom)
{
    enum { MAX_LINES = 4, LINE_CHARS = 192 };
    char  lines[MAX_LINES][LINE_CHARS];
    int   n = 0, scale, line_px, gap, pad, max_px, block_h, y, i;
    const char *p;

    if (!text || !text[0])
        return;

    scale   = size == UI_SUB_SMALL ? 2 : (size == UI_SUB_LARGE ? 4 : 3);
    line_px = font_px(scale);              /* design pixels */
    gap     = 8;
    pad     = 14;
    max_px  = DESIGN_W - 400;
    if (max_px < 480)
        max_px = 480;

    p = text;
    while (*p && n < MAX_LINES) {
        const char *pe = strchr(p, '\n');
        const char *end = pe ? pe : p + strlen(p);
        const char *wd = p;
        char cur[LINE_CHARS];

        cur[0] = '\0';
        while (wd < end && n < MAX_LINES) {
            const char *we;
            char trial[LINE_CHARS];

            while (wd < end && *wd == ' ')
                wd++;
            we = wd;
            while (we < end && *we != ' ')
                we++;
            if (we == wd)
                break;

            if (cur[0])
                snprintf(trial, sizeof(trial), "%s %.*s", cur,
                         (int)(we - wd), wd);
            else
                snprintf(trial, sizeof(trial), "%.*s", (int)(we - wd), wd);

            if (!cur[0] || text_width(trial, scale) <= max_px) {
                snprintf(cur, sizeof(cur), "%s", trial);
            } else {
                fit_text(lines[n], LINE_CHARS, cur, max_px, scale);
                n++;
                snprintf(cur, sizeof(cur), "%.*s", (int)(we - wd), wd);
            }
            wd = we;
        }
        if (cur[0] && n < MAX_LINES)
            fit_text(lines[n++], LINE_CHARS, cur, max_px, scale);
        if (!pe)
            break;
        p = pe + 1;
    }

    if (n == 0)
        return;

    block_h = n * (line_px + gap) + 2 * pad;
    y = bottom - block_h;
    if (y < 0)
        y = 0;

    /* one plate behind the whole block: separate boxes per line read as two
     * unrelated captions */
    {
        int widest = 0;
        for (i = 0; i < n; i++) {
            int tw = text_width(lines[i], scale);
            if (tw > widest)
                widest = tw;
        }
        SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
        SDL_SetRenderDrawColor(r, 0, 0, 0, 165);
        round_rect(r, (DESIGN_W - widest)/2 - 24, y, widest + 48, block_h, 10);
        SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_NONE);
    }

    for (i = 0; i < n; i++)
        text_center(r, DESIGN_W/2, y + pad + i * (line_px + gap), scale,
                    lines[i], C_TEXT);
}

/* A short confirmation over the picture: subtitle on/off and similar. It has
 * its own opacity so it can fade out instead of popping away. */
static void draw_toast(SDL_Renderer *r, const char *text, int alpha)
{
    const int h = 68, y = 84;
    int w, x, ty;

    if (!text || !text[0] || alpha <= 0)
        return;
    if (alpha > 255) alpha = 255;

    w  = text_width(text, 2) + 64;
    x  = (DESIGN_W - w) / 2;
    ty = y + (h - font_px(2)) / 2;

    round_rect_a(r, x, y, w, h, h/2, 8, 11, 18, alpha * 4 / 5);
    text_at_a(r, x + 32, ty, 2, text, C_TEXT_R, C_TEXT_G, C_TEXT_B, alpha);
}

